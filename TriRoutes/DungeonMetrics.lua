local function norm(s)
    s = string.lower(tostring(s or ""))
    s = string.gsub(s, "[^%a%d]", "")
    if string.sub(s, 1, 3) == "the" then s = string.sub(s, 4) end
    return s
end
M.Normalize = norm
function M:CanonicalMapFile(rawMapFile, instanceName)
    local ik = norm(instanceName)
    local alias = self.aliases[ik]
    if alias and self.byName[alias] then return alias end
    return rawMapFile
end
function M:Get(mapFile, areaID, floor, instanceName)
    local e
    -- WDM-restored instance maps can expose a stale/mismatched numeric area ID
    -- (for example TheStockade may report 691, which is Gnomeregan in the
    -- stock map table). Prefer the explicit map file and instance identity,
    -- and only use areaID as a final fallback.
    if mapFile and self.byName[mapFile] then e = self.byName[mapFile] end
    if not e then
        local nk = norm(mapFile)
        local ik = norm(instanceName)
        local alias = self.aliases[ik] or self.aliases[nk]
        if alias then e = self.byName[alias] end
        if not e then
            for name, candidate in pairs(self.byName) do
                local ck = norm(name)
                if (nk ~= "" and (ck == nk or string.find(nk, ck, 1, true) or string.find(ck, nk, 1, true)))
                    or (ik ~= "" and (ck == ik or string.find(ik, ck, 1, true) or string.find(ck, ik, 1, true))) then
                    e = candidate
                    break
                end
            end
        end
    end
    if (not e) and areaID and self.byArea[tonumber(areaID)] then e = self.byArea[tonumber(areaID)] end
    if not e then return nil end
    floor = tonumber(floor) or 0
    local f = e.floors[floor]
    if not f or floor <= 0 then f = e.floors[1] end
    if not f then
        for _, v in pairs(e.floors) do f = v break end
    end
    if not f then return nil end
    return f[1], f[2], e
end
